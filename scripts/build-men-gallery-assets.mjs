const sizes = [
  [400, 533, 78],
  [800, 1067, 82],
  [1200, 1600, 85],
];

let created = 0;
const requestedGalleries = process.argv.slice(2);
const galleryEntries = Object.entries(galleries).filter(([gallery]) =>
  requestedGalleries.length === 0 || requestedGalleries.includes(gallery)
);

if (requestedGalleries.length > 0 && galleryEntries.length !== requestedGalleries.length) {
  const found = new Set(galleryEntries.map(([gallery]) => gallery));
  const missing = requestedGalleries.filter((gallery) => !found.has(gallery));
  throw new Error(`Unknown galleries: ${missing.join(', ')}`);
}

for (const [gallery, sources] of galleryEntries) {
  const outputRoot = new URL(`../public/images/ideas/${gallery}/`, import.meta.url);
  await fs.mkdir(outputRoot, { recursive: true });

  for (const [index, source] of sources.entries()) {
    const number = String(index + 1).padStart(2, '0');
    const input = path.join(sourceRoot, source);

    for (const [width, height, quality] of sizes) {
      const output = fileURLToPath(new URL(`${number}-${width}.webp`, outputRoot));
      await sharp(input)
        .resize(width, height, { fit: 'cover', position: 'attention' })
        .webp({ quality, effort: 5 })
        .toFile(output);
      created += 1;
    }
  }
}

